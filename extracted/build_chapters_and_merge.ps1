# Helper function: Given a page number (or page range string like "410-411"), return Part, Chapter, Section info
function Get-PageContext([string]$pageStr) {
    $clean = $pageStr.Trim() -replace '–', '-'
    $firstPart = ($clean -split '-')[0].Trim()
    $pg = 0
    if (-not [int]::TryParse($firstPart, [ref]$pg)) {
        return $null
    }

    $matchedPart = $null
    foreach ($pt in $parts) {
        if ($pg -ge $pt.start_page) { $matchedPart = $pt }
    }

    $matchedChap = $null
    foreach ($ch in $chapters) {
        if ($pg -ge $ch.start_page) { $matchedChap = $ch }
    }

    $matchedSec = $null
    if ($matchedChap) {
        foreach ($sc in $matchedChap.sections) {
            if ($pg -ge $sc.start_page) { $matchedSec = $sc }
        }
    }

    $matchedSub = $null
    if ($matchedSec) {
        foreach ($sb in $matchedSec.subsections) {
            if ($pg -ge $sb.start_page) { $matchedSub = $sb }
        }
    }

    return [ordered]@{
        page = $pageStr
        part = if ($matchedPart) { "$($matchedPart.id): $($matchedPart.title)" } else { "" }
        chapter = if ($matchedChap) { "$($matchedChap.id): $($matchedChap.title)" } else { "" }
        section = if ($matchedSec) { "$($matchedSec.id) $($matchedSec.title)" } else { "" }
        subsection = if ($matchedSub) { $matchedSub.title } else { "" }
    }
}

